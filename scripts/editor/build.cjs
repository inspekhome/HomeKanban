'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const esbuild=require('esbuild'),root=path.resolve(__dirname,'../..'),vendor=path.join(root,'app/public/vendor');
(async()=>{
 const result=await esbuild.build({absWorkingDir:__dirname,entryPoints:['entry.js'],bundle:true,write:false,format:'iife',globalName:'HomeKanbanQuillModule',platform:'browser',target:['chrome110','edge110'],minify:true,metafile:true,legalComments:'inline'});
 const code=result.outputFiles[0].text;
 assert.doesNotMatch(code,/\b(?:execCommand|queryCommandState|queryCommandValue)\b/,'The editor must not depend on removed editing commands');
 // Delay DOM-dependent initialization until the first note is opened.
 const bundled='/* HomeKanban offline editor: Quill 2.0.3. See editor-LICENSES.txt. Generated by scripts/editor/build.cjs. */\nvar HomeKanbanRichText=(()=>{let loaded;return ()=>{if(!loaded){\n'+code+'\nloaded=HomeKanbanQuillModule;}return loaded;};})();\n';
 const packages=new Map();
 for(const input of Object.keys(result.metafile.inputs)){
  const match=input.replaceAll('\\','/').match(/node_modules\/((?:@[^/]+\/)?[^/]+)/);if(!match)continue;
  const name=match[1],dir=path.join(__dirname,'node_modules',name),meta=JSON.parse(fs.readFileSync(path.join(dir,'package.json'),'utf8'));
  const licenseFile=fs.readdirSync(dir).find(file=>/^licen[sc]e(?:\.txt|\.md)?$/i.test(file));assert.ok(licenseFile,'Missing license: '+name);
  packages.set(name,`${name} ${meta.version} (${meta.license})\n${'='.repeat(70)}\n${fs.readFileSync(path.join(dir,licenseFile),'utf8').trim()}\n`);
 }
 fs.mkdirSync(vendor,{recursive:true});fs.writeFileSync(path.join(vendor,'editor.js'),bundled);
 fs.writeFileSync(path.join(vendor,'editor-LICENSES.txt'),[...packages].sort(([a],[b])=>a.localeCompare(b)).map(([,text])=>text).join('\n'));
 console.log(JSON.stringify({bytes:Buffer.byteLength(bundled),components:[...packages.keys()].sort()}));
})().catch(error=>{console.error(error);process.exitCode=1;});
